import React, { useState } from "react";
import {
  OctagonAlert,
  TriangleAlert,
  Diamond,
  Circle,
  CheckCircle2,
  ArrowRight,
  ShieldCheck,
  ExternalLink,
  XCircle,
  Sparkles,
  Cpu,
} from "lucide-react";
import { motion } from "motion/react";
import type { Finding, EvidenceRef } from "../types";

interface Props {
  finding: Finding;
  onApplyFix?: (finding: Finding) => void;
  onDismiss?: (finding: Finding, reason: string) => void;
  onSelectEvidence?: (evidence: EvidenceRef) => void;
  isFocused?: boolean;
}

export const FindingCard: React.FC<Props> = ({
  finding,
  onApplyFix,
  onDismiss,
  onSelectEvidence,
  isFocused = false,
}) => {
  const [showDismissInput, setShowDismissInput] = useState(false);
  const [dismissReason, setDismissReason] = useState("");

  // Section 1 Severity Specification
  const severityConfig = {
    critical: {
      border: "border-l-critical",
      badge: "bg-critical/20 text-critical border-critical/40",
      icon: OctagonAlert,
      label: "Critical",
    },
    high: {
      border: "border-l-high",
      badge: "bg-high/20 text-high border-high/40",
      icon: TriangleAlert,
      label: "High",
    },
    medium: {
      border: "border-l-medium",
      badge: "bg-medium/20 text-medium border-medium/40",
      icon: Diamond,
      label: "Medium",
    },
    low: {
      border: "border-l-low",
      badge: "bg-low/20 text-low border-low/40",
      icon: Circle,
      label: "Low",
    },
  }[finding.severity] || {
    border: "border-l-muted",
    badge: "bg-white/10 text-muted border-line",
    icon: Circle,
    label: "Low",
  };

  const Icon = severityConfig.icon;
  const isResolved = finding.resolution !== "open";
  const isCritical = finding.severity === "critical";
  const isGemini = finding.source_engine === "llm" || finding.source_engine === "gemini";

  const handleDismissSubmit = (e: React.FormEvent) => {
    e.preventDefault();
    if (!dismissReason.trim()) return;
    onDismiss?.(finding, dismissReason);
    setShowDismissInput(false);
  };

  return (
    <motion.div
      initial={{ opacity: 0, y: 8 }}
      animate={{ opacity: 1, y: 0 }}
      transition={{ duration: 0.2 }}
      className={`relative p-5 rounded-2xl bg-card border border-line border-l-[3px] ${
        severityConfig.border
      } card-frame-hover ${
        isFocused ? "ring-2 ring-primary shadow-[0_0_24px_rgba(175,230,7,0.25)] bg-card/90 frame-pulse" : "hover:border-primary/40"
      } ${isResolved ? "opacity-75" : ""}`}
    >
      {/* Gemini Subtle Top-Right Stamp */}
      {isGemini && (
        <div className="absolute top-3 right-3 select-none pointer-events-none opacity-30 flex items-center gap-1 text-[9px] font-mono font-bold tracking-widest text-blue-400 uppercase">
          <Sparkles size={10} className="text-blue-400" />
          <span>Gemini Output</span>
        </div>
      )}

      {/* Header: Severity Badge + AI/Module Chip + Category */}
      <div className="flex items-center justify-between gap-2">
        <div className="flex items-center gap-2">
          {/* Severity Badge: Icon + Label + Color (WCAG 1.4.1) */}
          <span
            className={`px-2.5 py-0.5 rounded-full text-[11px] font-bold uppercase font-mono border flex items-center gap-1.5 ${
              severityConfig.badge
            } ${isCritical && !isResolved ? "animate-[pulse_1.5s_ease-in-out_2]" : ""}`}
          >
            <Icon size={12} />
            <span>{severityConfig.label}</span>
          </span>

          {/* Explicit AI Module Identification Chip */}
          {isGemini ? (
            <span
              title="Finding generated and verified by Google Gemini Cloud LLM"
              className="px-2.5 py-0.5 rounded-full bg-gradient-to-r from-blue-500/20 via-indigo-500/20 to-purple-500/20 border border-blue-400/50 text-blue-300 text-[10px] font-mono font-semibold flex items-center gap-1.5 shadow-[0_0_12px_rgba(59,130,246,0.3)] animate-in fade-in"
            >
              <Sparkles size={11} className="text-blue-400 animate-pulse" />
              <span>Google Gemini</span>
            </span>
          ) : (
            <span
              title="Finding generated by BrandGuard Local SLM & Rules Engine"
              className="px-2 py-0.5 rounded-full bg-primary/10 border border-primary/30 text-primary text-[10px] font-mono font-semibold flex items-center gap-1"
            >
              <Cpu size={11} className="text-primary" />
              <span>BrandGuard Module</span>
            </span>
          )}

          <span className="text-xs font-mono text-muted uppercase">
            {finding.category.replace(/_/g, " ")}
          </span>
        </div>

        {/* Resolution State */}
        {isResolved ? (
          <span className="flex items-center gap-1 text-[11px] font-semibold text-success font-mono">
            <CheckCircle2 size={12} />
            <span>{finding.resolution.toUpperCase()}</span>
          </span>
        ) : (
          <span className="text-[10px] font-mono text-muted/60">
            [{finding.excerpt.start}:{finding.excerpt.end}]
          </span>
        )}
      </div>

      {/* Flagged Excerpt */}
      <div className="mt-3 p-3 rounded-xl bg-[#0E0E0B] border border-line font-mono text-xs text-ink flex items-start justify-between gap-2">
        <div>
          <span className="text-[10px] text-muted block font-sans">Flagged text:</span>
          <span className="text-white font-semibold underline decoration-critical/70 underline-offset-2">
            "{finding.excerpt.text}"
          </span>
        </div>
      </div>

      {/* Explanation */}
      <p className="mt-2.5 text-xs text-muted leading-relaxed font-sans">{finding.explanation}</p>

      {/* Suggested Fix with Engine-Specific Watermarking */}
      {finding.suggested_correction && !isResolved && (
        <div
          className={`mt-3 p-3.5 rounded-xl border relative overflow-hidden flex flex-col gap-2 ${
            isGemini
              ? "bg-gradient-to-br from-blue-950/20 via-[#0E0E0B] to-indigo-950/30 border-blue-500/40 shadow-[0_0_20px_rgba(59,130,246,0.12)]"
              : "bg-success/10 border-success/30"
          }`}
        >
          {/* Faint Background Watermark for Gemini */}
          {isGemini && (
            <div className="absolute right-2 -bottom-2 select-none pointer-events-none opacity-10 flex items-center gap-1 text-[32px] font-black font-mono tracking-tighter text-blue-300">
              <Sparkles size={28} />
              <span>GEMINI</span>
            </div>
          )}

          {/* Suggestion Header with Explicit Watermark Pill */}
          <div className="flex items-center justify-between relative z-10">
            <div className="flex items-center gap-2">
              <span
                className={`text-[10px] uppercase font-mono font-bold flex items-center gap-1 ${
                  isGemini ? "text-blue-400" : "text-success"
                }`}
              >
                {isGemini ? <Sparkles size={11} className="text-blue-400" /> : <Cpu size={11} className="text-primary" />}
                <span>Suggested correction</span>
              </span>

              {isGemini ? (
                <span className="flex items-center gap-1 px-2 py-0.5 rounded-full bg-blue-500/25 border border-blue-400/50 text-[9px] font-mono font-bold text-blue-200 tracking-wider shadow-[0_0_10px_rgba(59,130,246,0.3)]">
                  <span>✨ GEMINI WATERMARK</span>
                </span>
              ) : (
                <span className="flex items-center gap-1 px-2 py-0.5 rounded-full bg-primary/10 border border-primary/30 text-[9px] font-mono font-bold text-primary tracking-wider">
                  <span>⚡ BRANDGUARD MODULE</span>
                </span>
              )}
            </div>

            {onApplyFix && (
              <motion.button
                whileHover={{ y: -1 }}
                whileTap={{ scale: 0.98 }}
                onClick={() => onApplyFix(finding)}
                className={`px-2.5 py-1 rounded-lg font-semibold text-xs transition-all flex items-center gap-1 shadow-sm ${
                  isGemini
                    ? "bg-gradient-to-r from-blue-500 to-indigo-600 hover:from-blue-400 hover:to-indigo-500 text-white shadow-[0_0_12px_rgba(59,130,246,0.35)]"
                    : "bg-success text-black hover:bg-success/90"
                }`}
              >
                <span>Apply suggestion</span>
                <ArrowRight size={12} />
              </motion.button>
            )}
          </div>

          {/* Suggestion Text with Watermarked Footer */}
          <div className="relative z-10">
            <p
              className={`text-xs font-mono p-2.5 rounded-lg border leading-relaxed ${
                isGemini
                  ? "text-blue-100 bg-[#0E0E0B]/90 border-blue-500/30"
                  : "text-success bg-[#0E0E0B]/60 border-success/20"
              }`}
            >
              {finding.suggested_correction}
            </p>
            {isGemini && (
              <div className="mt-1.5 flex items-center justify-between text-[9px] font-mono text-blue-400/80 px-1 pt-1 border-t border-blue-500/20">
                <span className="flex items-center gap-1">
                  <Sparkles size={9} /> Verified Grounding: Google Gemini 1.5 Cloud Model
                </span>
                <span className="opacity-70 uppercase tracking-widest font-semibold">Authentic AI Watermark</span>
              </div>
            )}
          </div>
        </div>
      )}

      {/* Evidence Citation & Actions Footer */}
      <div className="mt-3.5 pt-3 border-t border-line flex flex-wrap items-center justify-between gap-2">
        <button
          onClick={() => onSelectEvidence?.(finding.evidence)}
          className="flex items-center gap-1.5 px-2.5 py-1 rounded-lg bg-white/5 hover:bg-white/10 border border-line text-[11px] text-primary transition-colors font-mono"
        >
          <ShieldCheck size={12} />
          <span>{finding.evidence.label || finding.evidence.id}</span>
          <ExternalLink size={10} className="text-muted" />
        </button>

        {!isResolved && onDismiss && (
          <div>
            {isCritical ? (
              <span
                title="Critical findings cannot be dismissed per brand compliance governance."
                className="text-[10px] font-mono text-muted/50 cursor-not-allowed"
              >
                Dismissal blocked (Critical)
              </span>
            ) : showDismissInput ? (
              <form onSubmit={handleDismissSubmit} className="flex items-center gap-1">
                <input
                  type="text"
                  placeholder="Reason for dismissal..."
                  value={dismissReason}
                  onChange={(e) => setDismissReason(e.target.value)}
                  className="px-2 py-1 text-xs bg-[#0E0E0B] border border-line rounded-lg text-white focus:outline-none focus:border-primary"
                  autoFocus
                />
                <button
                  type="submit"
                  disabled={!dismissReason.trim()}
                  className="px-2 py-1 bg-white/10 hover:bg-white/20 text-white rounded-lg text-xs font-semibold disabled:opacity-50"
                >
                  Confirm
                </button>
                <button
                  type="button"
                  onClick={() => setShowDismissInput(false)}
                  className="p-1 text-muted hover:text-white"
                >
                  <XCircle size={14} />
                </button>
              </form>
            ) : (
              <button
                onClick={() => setShowDismissInput(true)}
                className="text-[11px] text-muted hover:text-white transition-colors underline underline-offset-2"
              >
                Dismiss with justification
              </button>
            )}
          </div>
        )}
      </div>
    </motion.div>
  );
};
